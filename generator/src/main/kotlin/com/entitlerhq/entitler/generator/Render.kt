package com.entitlerhq.entitler.generator

import com.entitlerhq.entitler.FeatureList
import com.entitlerhq.entitler.FeatureListing
import com.entitlerhq.entitler.FeatureType

private const val MAX_LINE = 140
private const val INDENT = "    "

private val keywords =
    setOf(
        "as",
        "break",
        "class",
        "continue",
        "do",
        "else",
        "false",
        "for",
        "fun",
        "if",
        "in",
        "interface",
        "is",
        "null",
        "object",
        "package",
        "return",
        "super",
        "this",
        "throw",
        "true",
        "try",
        "typealias",
        "typeof",
        "val",
        "var",
        "when",
        "while",
    )

private val existingConstant = Regex("""val\s+`?([A-Za-z_][A-Za-z0-9_]*)`?\s*:\s*Feature\.\w+\s*=\s*Feature\.\w+\(\s*"([^"]+)"""")

/** The comment line that names where the features were read from; `--check` ignores it. */
internal const val READ_FROM = "// Read from "

/**
 * Renders the Kotlin source of an `object Features` holding one typed constant per feature, sorted by key.
 *
 * When [existing] holds an earlier generated file, each feature keeps the constant name it had there, so
 * adding a feature never renames another.
 *
 * ```kotlin
 * val source = renderFeatures(server.features(), packageName = "com.example")
 * ```
 *
 * @param packageName The package to declare, or null for none.
 * @param existing The current contents of the output file, or null.
 */
public fun renderFeatures(
    features: FeatureList,
    packageName: String? = null,
    existing: String? = null,
): String {
    val sorted = features.features.sortedBy { it.key }
    val names = namesFor(sorted.map { it.key }, existing)
    val byKey = features.features.associateBy { it.key }
    val source = features.change?.let { "change $it" } ?: "release ${features.release}"
    val out = StringBuilder()
    out.append("// Generated by entitler generate. Do not edit.\n")
    out.append("$READ_FROM${features.environment.name}, ${features.track.name}, $source.\n\n")
    packageName?.let { out.append("package $it\n\n") }
    out.append("import com.entitlerhq.entitler.Feature\n")
    if (sorted.any { typeName(it.type) == null }) out.append("import com.entitlerhq.entitler.FeatureType\n")
    out.append("\n/** The features in the Entitler catalogue, generated by entitler generate. */\n")
    if (sorted.isEmpty()) return out.append("public object Features\n").toString()
    out.append("public object Features {\n")
    out.append(sorted.joinToString("\n") { constant(it, names.getValue(it.key), byKey) })
    out.append("}\n")
    return out.toString()
}

private fun namesFor(
    keys: List<String>,
    existing: String?,
): Map<String, String> {
    val kept = existing?.let { text -> existingConstant.findAll(text).associate { it.groupValues[2] to it.groupValues[1] } }.orEmpty()
    val names = keys.filter { it in kept }.associateWith { kept.getValue(it) }.toMutableMap()
    val taken = names.values.toMutableSet()
    for (key in keys.filter { it !in names }) {
        val base = camelCase(key).let { if (it in keywords || !it.first().isLetter()) "${it}_" else it }
        var name = base
        var suffix = 2
        while (name in taken) name = base + suffix++
        names[key] = name
        taken += name
    }
    return names
}

internal fun camelCase(key: String): String {
    val parts = key.split('_').filter { it.isNotEmpty() }
    if (parts.isEmpty()) return "feature"
    return parts.first() + parts.drop(1).joinToString("") { part -> part.replaceFirstChar { it.uppercase() } }
}

private fun typeName(type: FeatureType): String? =
    when (type) {
        FeatureType.Boolean -> "OnOff"
        FeatureType.Config -> "Setting"
        FeatureType.Metered -> "Metered"
        FeatureType.Group -> "Group"
        else -> null
    }

private fun constant(
    feature: FeatureListing,
    name: String,
    byKey: Map<String, FeatureListing>,
): String {
    val out = StringBuilder()
    out.append(docComment(feature))
    if (feature.archived) out.append("$INDENT@Deprecated(\"Archived in Entitler.\")\n")
    val type = typeName(feature.type)
    val declared = if (type == null) "Feature.Unknown" else "Feature.$type"
    val arguments =
        when (type) {
            null -> listOf(quote(feature.key), "FeatureType(${quote(feature.type.value)})")
            "Group" -> listOf(quote(feature.key), "listOf(${leaves(feature.key, byKey).joinToString(", ") { quote(it) }})")
            else -> listOf(quote(feature.key))
        }
    val call = "$declared(${arguments.joinToString(", ")})"
    val head = "${INDENT}public val $name: $declared ="
    when {
        "$head $call".length <= MAX_LINE -> out.append("$head $call\n")
        "$INDENT$INDENT$call".length <= MAX_LINE -> out.append("$head\n$INDENT$INDENT$call\n")
        else -> out.append("$head\n").append(wrapped(declared, feature.key, leaves(feature.key, byKey)))
    }
    return out.toString()
}

private fun wrapped(
    declared: String,
    key: String,
    members: List<String>,
): String {
    val indent = INDENT.repeat(2)
    return buildString {
        append("$indent$declared(\n")
        append("$indent$INDENT${quote(key)},\n")
        append("$indent${INDENT}listOf(\n")
        members.forEach { append("$indent$INDENT$INDENT${quote(it)},\n") }
        append("$indent$INDENT),\n")
        append("$indent)\n")
    }
}

private fun docComment(feature: FeatureListing): String {
    val paragraphs = mutableListOf(listOf(feature.name.ifBlank { feature.key }))
    feature.description
        .lines()
        .map { it.trim() }
        .filter { it.isNotEmpty() }
        .takeIf { it.isNotEmpty() }
        ?.let { paragraphs += it }
    if (feature.unit.isNotBlank()) paragraphs += listOf("Counted in ${feature.unit}.")
    if (feature.type == FeatureType.Group &&
        feature.includes.isNotEmpty()
    ) {
        paragraphs += listOf("Includes ${feature.includes.joinToString(", ")}.")
    }
    val lines = paragraphs.flatMapIndexed { index, lines -> if (index == 0) lines else listOf("") + lines }
    return buildString {
        append("$INDENT/**\n")
        lines.forEach { append(if (it.isEmpty()) "$INDENT *\n" else "$INDENT * ${it.replace("*/", "*&#47;")}\n") }
        append("$INDENT */\n")
    }
}

private fun leaves(
    key: String,
    byKey: Map<String, FeatureListing>,
): List<String> {
    val found = LinkedHashSet<String>()
    val visiting = mutableSetOf<String>()

    fun visit(current: String) {
        val feature = byKey[current] ?: return
        if (feature.type != FeatureType.Group) {
            found += current
            return
        }
        if (!visiting.add(current)) return
        feature.includes.forEach(::visit)
    }
    byKey[key]?.includes?.forEach(::visit)
    return found.toList()
}

private fun quote(value: String): String = "\"" + value.replace("\\", "\\\\").replace("\"", "\\\"").replace("$", "\\$") + "\""
